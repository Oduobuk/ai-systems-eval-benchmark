from typing import List, Dict, Any
try:
    from tabulate import tabulate
except ImportError:
    def tabulate(data, headers=(), tablefmt="github"):
        headers = list(headers)
        rows = [[str(cell) for cell in row] for row in data]
        col_widths = [len(h) for h in headers] if headers else [0] * (len(rows[0]) if rows else 0)
        for row in rows:
            for i, cell in enumerate(row):
                if i >= len(col_widths):
                    col_widths.append(len(cell))
                else:
                    col_widths[i] = max(col_widths[i], len(cell))
        lines = []
        if headers:
            lines.append("| " + " | ".join(h.ljust(col_widths[i]) for i, h in enumerate(headers)) + " |")
            lines.append("|-" + "-|-".join("-" * col_widths[i] for i in range(len(headers))) + "-|")
        for row in rows:
            lines.append("| " + " | ".join(cell.ljust(col_widths[i]) for i, cell in enumerate(row)) + " |")
        return "\n".join(lines)
from .schema import EvaluationResult


def generate_markdown_report(
    results: List[EvaluationResult],
    summary: Dict[str, Any]
) -> str:
    """
    Format evaluation results into a comprehensive Markdown benchmark report and leaderboard.
    """
    lines = [
        "# AI Systems Evaluation Benchmark: Official Evaluation Report",
        "\n*Generated by AI Systems Evaluation Benchmark Suite — Author: David Oduobuk*\n",
        "## 🏆 Benchmark Leaderboard\n"
    ]

    # Leaderboard Table
    leaderboard_data = []
    # Sort models by average composite score descending
    sorted_models = sorted(summary.items(), key=lambda x: x[1]["average_composite_score"], reverse=True)

    for rank, (model, stats) in enumerate(sorted_models, start=1):
        leaderboard_data.append([
            f"#{rank}",
            model,
            f"{stats['average_composite_score']:.2f} / 5.0",
            f"{stats['average_percentage']:.1f}%",
            f"{stats['passed_scenarios']} / {stats['total_scenarios']}",
            f"{stats['pass_rate_pct']:.1f}%"
        ])

    headers_lead = ["Rank", "Model Evaluated", "Avg Score", "Percentage", "Passed / Total", "Pass Rate"]
    lines.append(tabulate(leaderboard_data, headers=headers_lead, tablefmt="github"))

    # Category Breakdown Table
    lines.append("\n## 📊 Category Breakdown\n")
    all_categories = sorted(list({cat for stats in summary.values() for cat in stats["category_breakdown"]}))
    cat_headers = ["Model"] + all_categories

    cat_data = []
    for model, stats in sorted_models:
        row = [model]
        for cat in all_categories:
            score = stats["category_breakdown"].get(cat, 0.0)
            row.append(f"{score:.1f}%")
        cat_data.append(row)

    lines.append(tabulate(cat_data, headers=cat_headers, tablefmt="github"))

    # Detailed Diagnostic Drilldown
    lines.append("\n## 🔍 Scenario Audit & Error Diagnostics\n")
    for res in results:
        status_icon = "✅ PASS" if res.passed else "❌ FAIL"
        lines.append(f"### {res.scenario_title} (`{res.scenario_id}`)")
        lines.append(f"**Model:** `{res.model_name}` | **Verdict:** {status_icon} | **Score:** {res.score.composite_score:.2f} / 5.0 ({res.score.percentage:.1f}%)")
        lines.append(f"**Category:** `{res.category.value}`\n")
        lines.append("```")
        lines.append(res.evaluator_critique)
        lines.append("```\n")

    return "\n".join(lines)

